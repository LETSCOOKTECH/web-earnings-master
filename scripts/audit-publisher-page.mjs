#!/usr/bin/env node
// Offline evidence triage only; NOT Google Search, accessibility certification or AdSense approval.
// Usage: node scripts/audit-publisher-page.mjs --file templates/v6/page-example.json
import fs from 'node:fs';import path from 'node:path';import {pathToFileURL} from 'node:url';
const isStr=s=>typeof s==='string'&&s.trim().length>0;
const urlOk=s=>{try{const u=new URL(s);return u.protocol==='https:'&&!!u.hostname;}catch{return false;}};
export function auditPublisherPage(p){
 const blockers=[],unknown=[],warnings=[],proof=[];
 if(!p||typeof p!=='object'||Array.isArray(p))return {status:'FAIL_KNOWN',blockers:['Expected a page manifest object'],unknown,warnings,proof};
 if(!urlOk(p.url))blockers.push('Page URL must be valid public HTTPS');
 if(!isStr(p.user_job))blockers.push('A real user_job must be specified');
 if(!isStr(p.page_type)||!['tool','original_guide','category','home','account','result','error','policy'].includes(p.page_type))blockers.push('Unknown page_type');
 if(!isStr(p.title)||!isStr(p.h1))blockers.push('Missing accessible HTML title/H1');
 if(!isStr(p.initial_html_description)||p.initial_html_description.trim().length<35)blockers.push('Meaningful initial HTML content required, not a decorative JS-only shell');
 if(p.response_status!==200){
  if(p.response_status===undefined||p.response_status===null)unknown.push('Actual HTTP status not observed');
  else if(['error','result'].includes(p.page_type)&&[404,410].includes(p.response_status))warnings.push('Correct error response should generally avoid serving ads');
  else blockers.push('Unexpected HTTP status for a public indexable page');
 }
 if(p.raw_html_verified!==true)unknown.push('No independently fetched raw HTML snapshot');
 if(p.canonical_valid!==true)unknown.push('Canonical/indexability needs owner/site verification');
 if(p.robots_allowed!==true)unknown.push('Actual crawler and WAF access not verified');
 if(p.accessible_keyboard_tested!==true)unknown.push('Full keyboard and screen reader checks not complete');
 if(p.page_type==='tool'){
  if(!Array.isArray(p.real_task_oracles)||p.real_task_oracles.length===0)blockers.push('Tool page must declare independent real output oracles');
  if(p.output_oracles_passed!==true)unknown.push('Real file/calculation oracles not executed; tool value unverified');
  if(p.claims_no_upload===true&&p.network_privacy_tested!==true)blockers.push('Local/private processing claim not supported by network interception');
  if(p.unsupported_input_handled!==true)unknown.push('Unsupported/malicious input handling unverified');
 }
 if(p.autogenerated_variant_only===true)blockers.push('Pure keyword-template variant lacks separately demonstrated user value');
 if(p.structured_data_claimed===true&&p.structured_data_matches_visible!==true)blockers.push('Structured data does not match visible user content');
 const evidence=Array.isArray(p.public_claims)?p.public_claims:[];
 for(const c of evidence){
  if(!isStr(c.text)||!urlOk(c.source_url)||!isStr(c.checked_on)||c.supported!==true)blockers.push('Unsupported or undated public claim: '+(c.text||'unknown'));
 }
 if(['account','result','error'].includes(p.page_type)&&p.ads_enabled===true)blockers.push('Private/results/error/loading pages require deliberate no-ads disposition; default block');
 if(p.ads_enabled===true){
  if(p.adjacent_to_primary_action===true)blockers.push('Ads adjacent to critical download/submit/file-picker controls');
  if(p.ads_imitate_download_button===true)blockers.push('Deceptive ad resembles download/navigation/control');
  if(p.ad_click_encouragement===true)blockers.push('Incentivized/encouraged ad clicks prohibited');
  if(p.ads_layout_reservation_tested!==true)unknown.push('Ad slot layout shift not verified');
  if(p.publisher_policy_content_reviewed!==true)unknown.push('Human publisher-content/policy review is missing');
  if(p.consent_region_reviewed!==true)unknown.push('Regional ad consent status not verified');
  if(p.publisher_account_approved!==true)unknown.push('Provider site/account approval not observed');
  if(p.ads_txt_verified!==true)unknown.push('Authorized ads.txt seller identity not verified');
  if(p.page_is_under_construction===true||p.publisher_content_absent===true)blockers.push('Ads on under-construction or missing-publisher-content page');
 }else warnings.push('Ads disabled on this page; no ad approval inferred');
 if(!Array.isArray(p.contextual_internal_links)||p.contextual_internal_links.length===0)unknown.push('Page discovery via genuine HTML anchors not verified');
 if(Array.isArray(p.contextual_internal_links))for(const href of p.contextual_internal_links){
  if(!isStr(href)||href.startsWith('javascript:'))blockers.push('Noncrawlable/unsafe internal link');
 }
 if(p.page_type==='tool'&&p.output_oracles_passed===true)proof.push('Tool oracle marked observed by input; fixture hashes/reproducibility must be inspected independently');
 if(p.raw_html_verified===true)proof.push('Raw HTML observed per supplied manifest; no network fetch performed here');
 return {status:blockers.length?'FAIL_KNOWN':unknown.length?'UNKNOWN_EXTERNAL':'OFFLINE_REVIEW_ONLY',page:p.url,blockers,unknown,warnings,proof,
 disclaimer:'This is manifest consistency review only. It does not execute browser/file tasks, confirm real Google indexation, site approval, ad network policy or revenue.'};
}
if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href){
 const i=process.argv.indexOf('--file');if(i<0||!process.argv[i+1]){console.error('Usage: node scripts/audit-publisher-page.mjs --file <manifest.json>');process.exitCode=2;}
 else try{const result=auditPublisherPage(JSON.parse(fs.readFileSync(process.argv[i+1],'utf8')));console.log(JSON.stringify(result,null,2));if(result.status==='FAIL_KNOWN')process.exitCode=1;}catch(e){console.error('INPUT_ERROR '+String(e));process.exitCode=2;}
}
